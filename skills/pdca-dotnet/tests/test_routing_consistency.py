def read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def norm(text: str) -> str:
    return re.sub(r"\s+", " ", text.replace("`", "").replace("*", "")).strip()


def _parse_block(block: str) -> dict:
    """Tiny indentation parser for the flat/sub-map frontmatter subset used here."""
    root: dict = {}
    stack: list[tuple[int, dict]] = [(-1, root)]
    for raw in block.splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        indent = len(raw) - len(raw.lstrip(" "))
        key, _, val = raw.strip().partition(":")
        key, val = key.strip().strip('"').strip("'"), val.strip().strip('"').strip("'")
        while stack and indent <= stack[-1][0]:
            stack.pop()
        if val == "":
            stack[-1][1][key] = {}
            stack.append((indent, stack[-1][1][key]))
        else:
            stack[-1][1][key] = val
    return root


def frontmatter(path: Path) -> dict:
    text = read(path)
    assert text.startswith("---"), f"{path}: no frontmatter"
    return _parse_block(text[3:text.find("\n---", 3)])


def _matches(pattern: str, value: str) -> bool:
    """Whole-value wildcard match: `*` = any run, `?` = one character."""
    regex = "".join(
        ".*" if ch == "*" else "." if ch == "?" else re.escape(ch) for ch in pattern)
    flags = re.IGNORECASE if os.name == "nt" else 0
    return re.fullmatch(regex, value, flags | re.DOTALL) is not None


# Published skill assets must stay V1-compatible: V1 knows only `permission:`, while
# V2 translates legacy frontmatter automatically. Host config is native V2.
V1_ACTION = {"subagent": "task", "shell": "bash"}


def legacy_permission(path: Path) -> dict:
    data = frontmatter(path)
    node = data.get("permission")
    if not isinstance(node, dict) or not node:
        raise AssertionError(f"{path}: expected a non-empty V1 `permission:` map")
    return node


def legacy_effective(perm: dict, action: str, resource: str) -> str:
    """V1 semantics: action key → effect or resource map (last match wins)."""
    node = perm.get(V1_ACTION.get(action, action))
    if node is None:
        node = perm.get("*")
    if node is None:
        return "allow"  # V1 default: the tool is not restricted
    if isinstance(node, str):
        return node
    effect = "ask"
    for pattern, value in node.items():
        if _matches(pattern, resource):
            effect = value
    return effect


def legacy_allowed(perm: dict, action: str) -> set:
    node = perm.get(V1_ACTION.get(action, action))
    if isinstance(node, str):
        return {"*"} if node == "allow" else set()
    if not isinstance(node, dict):
        return set()
    return {res for res in node if legacy_effective(perm, action, res) == "allow"}


class RolePermissionTest(unittest.TestCase):
    """Cheap orchestrator canonical allowlist; expensive roles stay narrow and mirror the assets."""

    def test_planner_and_check_have_no_subagent_permission(self):
        for role in ("pdca-planner", "pdca-check"):
            with self.subTest(role=role, base="asset"):
                perm = legacy_permission(ASSET_AGENTS / f"{role}.md")
                self.assertEqual(legacy_effective(perm, "*", "*"), "deny")
                self.assertEqual(legacy_effective(perm, "subagent", "*"), "deny")
                self.assertEqual(legacy_allowed(perm, "subagent"), set())

    def test_escalate_subagent_only_scout(self):
        perm = legacy_permission(ASSET_AGENTS / "pdca-escalate.md")
        self.assertEqual(legacy_effective(perm, "subagent", "*"), "deny")
        self.assertEqual(legacy_allowed(perm, "subagent"), {"pdca-scout"})

    def test_security_auditor_allows_exactly_three_skills(self):
        perm = legacy_permission(ASSET_AGENTS / "pdca-security-auditor.md")
        self.assertEqual(legacy_effective(perm, "skill", "*"), "deny")
        self.assertEqual(legacy_allowed(perm, "skill"), SEC_SKILLS)

    def test_asset_agents_keep_v1_permission_map_for_compat(self):
        # V1 only understands `permission:`; V2 translates it automatically.
        # A V2-only `permissions:` list would silently drop every restriction in V1.
        for path in sorted(ASSET_AGENTS.glob("*.md")):
            data = frontmatter(path)
            with self.subTest(path=path.name):
                self.assertIn("permission", data)
                self.assertNotIn("permissions", data)
                self.assertTrue(legacy_permission(path))

    def _assert_role_tiers_are_tier_comments(self, base: Path) -> None:
        for name, tier in TIERS.items():
            paths = [base / f"{name}.md"]
            for path in filter(Path.exists, paths):
                with self.subTest(path=str(path)):
                    self.assertRegex(read(path), rf"(?m)^# tier: {tier}\s*$")
                    self.assertNotRegex(read(path), r"(?m)^\s*#\s*model:")

    def test_all_role_tiers_are_tier_comments(self):
        self._assert_role_tiers_are_tier_comments(ASSET_AGENTS)


def _direction(root, edge_id: str) -> tuple:
    """Source/target from data-from/to when present, else from endpoint geometry."""
    edge = next(el for el in root.iter() if el.get("data-edge-id") == edge_id)
    if edge.get("data-from") and edge.get("data-to"):
        return edge.get("data-from"), edge.get("data-to")
    boxes = {}
    for el in root.iter():
        nid = el.get("data-node-id")
        if nid:
            boxes[nid] = tuple(float(el.get(a) or 0) for a in ("x", "y", "width", "height"))
    pts = [(float(a), float(b))
           for a, b in (p.split(",") for p in (edge.get("points") or "").split())]

    def dist(p, b) -> float:
        x, y, w, h = b
        return ((max(x - p[0], 0, p[0] - (x + w))) ** 2
                + (max(y - p[1], 0, p[1] - (y + h))) ** 2) ** 0.5

    nearest = lambda p: min(boxes, key=lambda n: dist(p, boxes[n]))
    return nearest(pts[0]), nearest(pts[-1])


class GeneratedDiagramTest(unittest.TestCase):
    """Freshness/determinism + structural selectors on freshly rendered SVG."""

    @classmethod
    def setUpClass(cls) -> None:
        env = dict(os.environ, PYTHONDONTWRITEBYTECODE="1")
        cls.dirs, cls.runs = [], []
        for _ in range(2):
            tmp = tempfile.TemporaryDirectory()
            shutil.copy(GEN, tmp.name)
            subprocess.run([sys.executable, "gen_pdca.py"], cwd=tmp.name, env=env, check=True,
                           capture_output=True, text=True)
            cls.dirs.append(tmp)
            cls.runs.append({n: (Path(tmp.name) / n).read_bytes() for n in OUTPUTS})

    @classmethod
    def tearDownClass(cls) -> None:
        for tmp in cls.dirs:
            tmp.cleanup()

    def test_generator_outputs_four_files_matching_assets(self):
        self.assertEqual(set(self.runs[0]), set(OUTPUTS))
        for name in OUTPUTS:
            with self.subTest(name=name):
                self.assertEqual(self.runs[0][name], (DIAGRAM / name).read_bytes())

    def test_generator_is_deterministic_across_runs(self):
        for name in OUTPUTS:
            with self.subTest(name=name):
                self.assertEqual(self.runs[0][name], self.runs[1][name])

    def test_named_edges_and_nodes_present_in_both_themes(self):
        expected_edges = {
            "check_security", "security_check_report", "security_escalate_tradeoff",
            "escalate_do_nonexhausted", "escalate_plan_exhausted", "escalate_stop", "check_act",
        }
        expected_nodes = {"PLAN", "DO", "CHECK", "ACT", "START", "EXIT",
                          "sec_check", "escalate", "stop"}
        for svg in ("pdca-hand.svg", "pdca-hand-dark.svg"):
            root = ET.fromstring(self.runs[0][svg])
            with self.subTest(svg=svg):
                edges = {el.get("data-edge-id") for el in root.iter() if el.get("data-edge-id")}
                nodes = {el.get("data-node-id") for el in root.iter() if el.get("data-node-id")}
                self.assertTrue(expected_edges <= edges)
                self.assertTrue(expected_nodes <= nodes)

    def test_svg_edge_directions_security_and_escalation(self):
        root = ET.fromstring(self.runs[0]["pdca-hand.svg"])
        expected = {
            "check_security": ("CHECK", "sec_check"),
            "security_check_report": ("sec_check", "CHECK"),
            "security_escalate_tradeoff": ("sec_check", "escalate"),
            "escalate_do_nonexhausted": ("escalate", "DO"),
            "escalate_plan_exhausted": ("escalate", "PLAN"),
            "escalate_stop": ("escalate", "stop"),
            "check_act": ("CHECK", "ACT"),
        }
        for edge_id, pair in expected.items():
            with self.subTest(edge=edge_id):
                self.assertEqual(_direction(root, edge_id), pair)

    def test_svg_condition_and_tradeoff_labels(self):
        for svg in ("pdca-hand.svg", "pdca-hand-dark.svg"):
            root = ET.fromstring(self.runs[0][svg])
            texts = " ".join(el.text or "" for el in root.iter() if el.tag.endswith("text"))
            with self.subTest(svg=svg):
                for token in ("not exhausted", "r exhausted", "r+1", "trade-off"):
                    self.assertIn(token, texts)

    def test_html_inlines_paired_svg_module_for_module(self):
        for html_name, svg_name in (("pdca-hand.html", "pdca-hand.svg"),
                                    ("pdca-hand-dark.html", "pdca-hand-dark.svg")):
            html = self.runs[0][html_name].decode("utf-8")
            match = re.search(r"<svg\b.*?</svg>", html, re.S)
            with self.subTest(html=html_name):
                self.assertEqual(html.count("<svg"), 1)
                if match is None:
                    self.fail("inline SVG not found")
                self.assertEqual(match.group(0).strip(),
                                 (DIAGRAM / svg_name).read_text(encoding="utf-8").strip())


class ContractTextTest(unittest.TestCase):
    """The operative contract of this overlay is its inheritance chain.

    A .NET overlay inherits the base cycle and the coder overlay, so the retained
    routing/safety rules are asserted over the whole chain (base → coder → .NET),
    not over the shortened overlay file alone.
    """

    @classmethod
    def setUpClass(cls) -> None:
        cls.base = SKILL_DIR.parent / "pdca/SKILL.md"
        cls.coder = SKILL_DIR.parent / "pdca-coder/SKILL.md"
        cls.references = sorted((SKILL_DIR / "references").glob("*.md"))
        cls.corpus = norm(" ".join(
            read(path) for path in [cls.base, cls.coder, SKILL] + cls.references
        ))

    def test_skill_critical_routing_tokens(self):
        missing = [token for token in CRITICAL_TOKENS if token not in self.corpus]
        self.assertEqual(missing, [])


if __name__ == "__main__":
    unittest.main()
